"""Generate the two-page report and the README results section from computed results.

Every number in the report comes from `reports/results/*`, so re-running the pipeline
can never leave the text out of sync with the figures.
"""

from __future__ import annotations

import calendar
import json
import re
from pathlib import Path

import pandas as pd

from conso_forecast.config import Settings
from conso_forecast.pipeline import RTE_NAME
from conso_forecast.plotting import MODEL_LABELS

README_START = "<!-- RESULTS:START -->"
README_END = "<!-- RESULTS:END -->"


def _read_json(path: Path) -> dict:
    if not path.exists():
        raise FileNotFoundError(f"{path} not found: run the previous pipeline steps first")
    return json.loads(path.read_text(encoding="utf-8"))


def improvement_pct(model_mae: float, reference_mae: float) -> float:
    """Relative MAE reduction of the model versus a reference, in percent."""
    return 100 * (1 - model_mae / reference_mae)


def metrics_table(metrics: pd.DataFrame) -> str:
    lines = ["| Model | MAE (MW) | RMSE (MW) | MAPE (%) |", "|---|---:|---:|---:|"]
    for name, row in metrics.sort_values("mae_mw").iterrows():
        lines.append(
            f"| {MODEL_LABELS.get(name, name)} | {row.mae_mw:,.0f} | {row.rmse_mw:,.0f} "
            f"| {row.mape_pct:.2f} |"
        )
    return "\n".join(lines)


def headline(metrics: pd.DataFrame, best: str, baseline: str) -> str:
    gain = improvement_pct(metrics.loc[best, "mae_mw"], metrics.loc[baseline, "mae_mw"])
    return (
        f"On the held-out test year, **{MODEL_LABELS[best]}** forecasts next-day hourly "
        f"consumption with a mean absolute error of **{metrics.loc[best, 'mae_mw']:,.0f} MW** "
        f"(**{metrics.loc[best, 'mape_pct']:.2f} %**), **{gain:.0f} % lower** than the best naive "
        f"baseline ({MODEL_LABELS[baseline].lower()}, {metrics.loc[baseline, 'mae_mw']:,.0f} MW)."
    )


def rte_sentence(metrics: pd.DataFrame, best: str) -> str:
    if RTE_NAME not in metrics.index:
        return "RTE's own forecast was not available in the downloaded data, so it is not compared."
    rte, ours = metrics.loc[RTE_NAME, "mae_mw"], metrics.loc[best, "mae_mw"]
    caveat = (
        "RTE publishes earlier and must use *forecast* weather, whereas we use *observed* "
        "temperatures (see Limitations)"
    )
    if ours < rte:
        return (
            f"RTE's official day-ahead forecast has an error of {rte:,.0f} MW, higher than ours, "
            f"but the comparison flatters our model: {caveat}."
        )
    return (
        f"RTE's official day-ahead forecast remains better ({rte:,.0f} MW), even though the "
        f"comparison favours our model: {caveat}."
    )


def build_report(settings: Settings) -> str:
    results = settings.paths.results
    metrics = pd.read_csv(results / "test_metrics.csv", index_col=0)
    eda = _read_json(results / "eda_summary.json")
    errors = _read_json(results / "error_analysis.json")
    quality = _read_json(results / "data_quality.json")
    best, baseline = errors["best_model"], errors["best_baseline"]

    by_month = {int(k): v[best] for k, v in errors["mae_by_month"].items()}
    by_hour = {int(k): v[best] for k, v in errors["mae_by_hour"].items()}
    worst_month = calendar.month_name[max(by_month, key=by_month.get)]
    best_month = calendar.month_name[min(by_month, key=by_month.get)]
    worst_hour = max(by_hour, key=by_hour.get)
    by_type = {k: v[best] for k, v in errors["mae_by_day_type"].items()}
    weekday_mae = by_type.get("Weekday", float("nan"))
    hardest_type = max(by_type, key=by_type.get)
    worst_days = "\n".join(
        f"- {d['date']}: {d['mae_mw']:,.0f} MW ({d['day_type'].lower()}, {d['temperature_c']} °C)"
        for d in errors["worst_days"][:5]
    )
    effects = eda["calendar_effects_pct"]
    features = ", ".join(f"`{f}`" for f in errors["top_features"])
    gradient_gw = eda["heating_gradient_mw_per_degree"] / 1000

    return f"""# Forecasting tomorrow's French electricity consumption

*Generated by `make report`. All figures come from the pipeline outputs.*

## Summary

{headline(metrics, best, baseline)}

## The problem

The French grid operator must balance production and consumption every second. Each day,
producers and traders need a forecast of the next day's consumption, hour by hour; every
forecast error has to be covered at short notice, at a higher cost. We build such a
forecast from public data and measure how much better it is than simple rules of thumb.

## The data

- **Consumption**: national hourly consumption published by RTE (eCO2mix, open data,
  Licence Ouverte), {eda["first_hour"][:10]} to {eda["last_hour"][:10]}
  ({eda["n_hours"]:,} hours; {quality["interpolated_hours"]} short gaps interpolated,
  {quality["missing_hours_after_cleaning"]} hours left missing).
- **Weather**: hourly temperature of the ten largest French cities (Open-Meteo, ERA5
  reanalysis, CC BY 4.0), averaged with population weights.
- **Calendar**: weekends, public holidays and "bridge" days.

What the data shows: consumption is {eda["winter_over_summer_ratio"]:.1f} times higher in
winter than in summer because of electric heating; below 15 °C, each degree colder adds
about **{gradient_gw:.1f} GW**. Sundays are
{abs(effects["Sunday"]):.0f} % below an ordinary weekday, public holidays
{abs(effects["Public holiday"]):.0f} % below.

![Temperature effect](figures/eda_temperature_effect.png)

## The approach

The forecast for day D+1 is made at the end of day D, using only what is known at that
time: past consumption, the calendar, and temperature. We compare:

1. **Two naive baselines**: repeat yesterday's value, or last week's value, for each hour.
2. **Ridge regression**: a linear model on the same inputs.
3. **LightGBM**: gradient-boosted decision trees, tuned by random search.

Models are chosen on {settings.val_start[:4]} (validation year) and evaluated once on the
test period starting {settings.test_start}, never seen during development.

## Results (test period)

{metrics_table(metrics)}

MAE: mean absolute error, in megawatts. MAPE: the same error as a percentage of consumption.

{rte_sentence(metrics, best)}

![Error by month](figures/errors_by_month.png)

## When does the model get it wrong?

- Errors are largest in **{worst_month}** and smallest in **{best_month}**; by hour, the
  hardest hour is **{worst_hour}:00**.
- Error on ordinary weekdays is {weekday_mae:,.0f} MW; the hardest day type is
  **{hardest_type.lower()}** ({by_type[hardest_type]:,.0f} MW).
- Most influential inputs: {features}.
- Worst days of the test period:

{worst_days}

## Limitations

- **Observed instead of forecast weather.** In real operations the temperature of
  tomorrow is itself a forecast, typically off by about 1 °C; with ~{gradient_gw:.1f} GW
  per °C in winter, real-world errors would be noticeably higher.
- **Forecast issued at midnight.** Market forecasts are needed around noon on day D;
  that setup only allows older consumption data.
- **Rare events** (holidays falling mid-week, cold snaps, strikes, the 2022 energy-saving
  effort) are few in the training data, and we model national demand only.

## Reproduce

```
git clone https://github.com/karissa410/conso-forecast && cd conso-forecast
make all
```
"""


def results_block(settings: Settings) -> str:
    results = settings.paths.results
    metrics = pd.read_csv(results / "test_metrics.csv", index_col=0)
    errors = _read_json(results / "error_analysis.json")
    best, baseline = errors["best_model"], errors["best_baseline"]
    return (
        f"{README_START}\n{headline(metrics, best, baseline)}\n\n"
        f"Test period: {settings.test_start} to {settings.end_date}.\n\n"
        f"{metrics_table(metrics)}\n\n{rte_sentence(metrics, best)}\n\n"
        f"![Example weeks](reports/figures/example_weeks.png)\n{README_END}"
    )


def update_readme(readme: str, block: str) -> str:
    pattern = re.compile(re.escape(README_START) + ".*?" + re.escape(README_END), re.DOTALL)
    if not pattern.search(readme):
        raise ValueError("README.md has no results markers")
    return pattern.sub(lambda _: block, readme)


def run_report(settings: Settings) -> Path:
    report_path = settings.paths.reports / "report.md"
    report_path.write_text(build_report(settings), encoding="utf-8")
    readme_path = settings.paths.root / "README.md"
    if readme_path.exists():
        readme_path.write_text(
            update_readme(readme_path.read_text(encoding="utf-8"), results_block(settings)),
            encoding="utf-8",
        )
    return report_path
